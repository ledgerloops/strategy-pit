"""Native hosted tables and the reviewed legacy-import column contract."""

DATA_SCHEMA = SCHEMA = 'ledgerloops_data'
TABLE = 'ledgerloops_nodes'
LEGACY_TABLE = 'ledgerloops_node_snapshots'

_DEFINITIONS = {
    'meta': ('k TEXT,v TEXT', ('k',)),
    'balances': ('peer TEXT,balance BIGINT NOT NULL', ('peer',)),
    'proposals': ('id TEXT,data TEXT NOT NULL,status TEXT NOT NULL,approved BIGINT DEFAULT 0,prev TEXT,next TEXT,origin BIGINT DEFAULT 0,prepared BIGINT DEFAULT 0,ready_seen BIGINT DEFAULT 0,ready_forwarded BIGINT DEFAULT 0,next_rejected INTEGER DEFAULT 0', ('id',)),
    'private_secrets': ('id TEXT,preimage TEXT NOT NULL', ('id',)),
    'reservations': ('peer TEXT,proposal TEXT NOT NULL', ('peer',)),
    'outbox': ('id TEXT,peer TEXT NOT NULL,data TEXT NOT NULL', ('id',)),
    'inbox': ('id TEXT', ('id',)),
    'searches': ('id TEXT,status TEXT NOT NULL', ('id',)),
    'contacts': ('peer TEXT,own TEXT NOT NULL,peer_preferences TEXT', ('peer',)),
    'receipts': ('id TEXT,data TEXT NOT NULL', ('id',)),
    'obligations': ('id TEXT,peer TEXT NOT NULL,data TEXT NOT NULL,digest TEXT NOT NULL,status TEXT NOT NULL,origin BIGINT NOT NULL,approved BIGINT NOT NULL,applied_at DOUBLE PRECISION,reason TEXT', ('id',)),
    'hosted_invites': ("token_hash TEXT,expires DOUBLE PRECISION NOT NULL,accepted_by TEXT,peer_key TEXT,peer_name TEXT NOT NULL DEFAULT '',max_trust BIGINT NOT NULL DEFAULT 10,accepted_max_trust BIGINT", ('token_hash',)),
    'hosted_messages': ('id TEXT NOT NULL,peer TEXT NOT NULL,direction TEXT NOT NULL,text TEXT NOT NULL,status TEXT NOT NULL,created_at DOUBLE PRECISION NOT NULL,sent_at DOUBLE PRECISION,received_at DOUBLE PRECISION,delivered_at DOUBLE PRECISION', ('peer', 'id', 'direction')),
    'channel_keys': ('pair TEXT,secret TEXT NOT NULL', ('pair',)),
    'auth_accounts': ('id TEXT,node_id TEXT NOT NULL,name TEXT NOT NULL,created BIGINT NOT NULL', ('id',)),
    'auth_credentials': ('id TEXT,account_id TEXT NOT NULL,public_key TEXT NOT NULL,sign_count BIGINT NOT NULL,created BIGINT NOT NULL', ('id',)),
    'auth_challenges': ('id TEXT,kind TEXT NOT NULL,challenge TEXT NOT NULL,context TEXT NOT NULL,expires BIGINT NOT NULL,consumed BIGINT NOT NULL DEFAULT 0', ('id',)),
    'auth_sessions': ('token_hash TEXT,account_id TEXT NOT NULL,csrf TEXT NOT NULL,expires BIGINT NOT NULL', ('token_hash',)),
    'auth_recovery': ('code_hash TEXT,account_id TEXT NOT NULL,consumed BIGINT NOT NULL DEFAULT 0', ('code_hash',)),
}
TABLES = {name: {'ddl': ddl, 'key': key,
                'columns': tuple(field.strip().split()[0] for field in ddl.split(','))}
          for name, (ddl, key) in _DEFINITIONS.items()}
TABLE_COLUMNS = {name: spec['columns'] for name, spec in TABLES.items()}


def initialize(connection):
    connection.execute(f'''CREATE TABLE IF NOT EXISTS public.{TABLE}(
        node_id TEXT PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        legacy_snapshot_version BIGINT, legacy_snapshot_sha256 TEXT)''')
    connection.execute(f'CREATE SCHEMA IF NOT EXISTS {SCHEMA}')
    connection.execute(f'''CREATE OR REPLACE FUNCTION {SCHEMA}.mark_dirty()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF TG_OP = 'UPDATE' AND NEW IS NOT DISTINCT FROM OLD THEN RETURN NEW; END IF;
            PERFORM pg_catalog.set_config('ledgerloops.dirty', '1', true);
            IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
            RETURN NEW;
        END $$''')
    scope = "owner_node_id = NULLIF(pg_catalog.current_setting('ledgerloops.owner_node_id', true), '')"
    for name, spec in TABLES.items():
        qualified = f'{SCHEMA}.{name}'
        connection.execute(f'''CREATE TABLE IF NOT EXISTS {qualified}(
            {spec['ddl']},
            owner_node_id TEXT NOT NULL DEFAULT NULLIF(pg_catalog.current_setting('ledgerloops.owner_node_id', true), '')
                REFERENCES public.{TABLE}(node_id) ON DELETE CASCADE,
            rowid BIGINT GENERATED BY DEFAULT AS IDENTITY,
            PRIMARY KEY(owner_node_id,{','.join(spec['key'])}))''')
        category = ("owner_node_id ~ '(^|:)accounts$'" if name.startswith('auth_') else
                    "owner_node_id ~ '(^|:)enrollment$'" if name == 'channel_keys' else
                    "owner_node_id !~ '(^|:)(accounts|enrollment)$'")
        connection.execute(f'ALTER TABLE {qualified} ENABLE ROW LEVEL SECURITY')
        connection.execute(f'ALTER TABLE {qualified} FORCE ROW LEVEL SECURITY')
        connection.execute(f'DROP POLICY IF EXISTS actor_scope ON {qualified}')
        connection.execute(f'''CREATE POLICY actor_scope ON {qualified}
            USING ({scope} AND {category}) WITH CHECK ({scope} AND {category})''')
        connection.execute(f'DROP TRIGGER IF EXISTS dirty ON {qualified}')
        connection.execute(f'''CREATE TRIGGER dirty AFTER INSERT OR UPDATE OR DELETE ON {qualified}
            FOR EACH ROW EXECUTE FUNCTION {SCHEMA}.mark_dirty()''')
        connection.execute(f'CREATE INDEX IF NOT EXISTS {name}_order ON {qualified}(owner_node_id,rowid)')
    connection.execute(f'CREATE UNIQUE INDEX IF NOT EXISTS auth_account_node ON {SCHEMA}.auth_accounts(owner_node_id,node_id)')
    connection.execute(f'CREATE INDEX IF NOT EXISTS messages_peer_time ON {SCHEMA}.hosted_messages(owner_node_id,peer,created_at)')
    connection.execute(f'CREATE INDEX IF NOT EXISTS credentials_account ON {SCHEMA}.auth_credentials(owner_node_id,account_id)')
    connection.execute(f'CREATE INDEX IF NOT EXISTS sessions_account ON {SCHEMA}.auth_sessions(owner_node_id,account_id)')
